import Joi from 'joi';
import { USER_ROLES } from '../utils/constants.js';

export const registerSchema = Joi.object({
  email: Joi.string().email({ tlds: { allow: false } }).required().messages({
    'string.email': 'Please provide a valid email address',
    'any.required': 'Email is required',
  }),
  password: Joi.string()
    .min(8)
    .pattern(/^(?=.*[a-z])(?=.*[A-Z])(?=.*\d)(?=.*[@$!%*?&])[A-Za-z\d@$!%*?&]/)
    .required()
    .messages({
      'string.min': 'Password must be at least 8 characters',
      'string.pattern.base': 'Password must contain uppercase, lowercase, number and special character',
      'any.required': 'Password is required',
    }),
  confirmPassword: Joi.string().valid(Joi.ref('password')).required().messages({
    'any.only': 'Passwords do not match',
    'any.required': 'Confirm password is required',
  }),
  firstName: Joi.string().trim().max(50).required().messages({
    'string.max': 'First name cannot exceed 50 characters',
    'any.required': 'First name is required',
  }),
  lastName: Joi.string().trim().max(50).required().messages({
    'string.max': 'Last name cannot exceed 50 characters',
    'any.required': 'Last name is required',
  }),
  phone: Joi.string().allow('', null),
  role: Joi.string().valid(USER_ROLES.MASTER, USER_ROLES.ESTABLISHMENT).required().messages({
    'any.only': 'Role must be either master or establishment',
    'any.required': 'Role is required',
  }),
  establishmentName: Joi.when('role', {
    is: USER_ROLES.ESTABLISHMENT,
    then: Joi.string().required().messages({
      'any.required': 'Establishment name is required for unit accounts',
    }),
    otherwise: Joi.string().optional().allow('', null),
  }),
  designation: Joi.string().optional().allow('', null),
  serviceNumber: Joi.string().optional().allow('', null),
});

export const loginSchema = Joi.object({
  email: Joi.string().email({ tlds: { allow: false } }).required().messages({
    'string.email': 'Please provide a valid email address',
    'any.required': 'Email is required',
  }),
  password: Joi.string().required().messages({
    'any.required': 'Password is required',
  }),
  rememberMe: Joi.boolean().default(false),
});

